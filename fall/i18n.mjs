export function t(key, vars) {
  let s = DICT[lang]?.[key] ?? DICT.de[key] ?? key
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => vars[k] ?? m)
  return s
}

// Statische Texte der Seite: data-t (Text), data-th (HTML), data-tp (placeholder), data-ta (aria-label), data-tt (title)
export function applyStatic(root = document) {
  const map = [['data-t', (el, v) => { el.textContent = v }], ['data-th', (el, v) => { el.innerHTML = v }], ['data-tp', (el, v) => el.setAttribute('placeholder', v)],
    ['data-ta', (el, v) => el.setAttribute('aria-label', v)], ['data-tt', (el, v) => el.setAttribute('title', v)]]
  for (const [attr, fn] of map) for (const el of root.querySelectorAll(`[${attr}]`)) fn(el, t(el.getAttribute(attr)))
}
