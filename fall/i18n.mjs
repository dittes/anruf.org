const get = k => { try { return localStorage.getItem('fall.' + k) } catch { return null } }
const put = (k, v) => { try { localStorage.setItem('fall.' + k, v) } catch {} }

export const ROOM_RE = /^(?:(en)\/)?([a-z0-9-]+)\/([a-z0-9-]+)$/i

function detect() {
  const m = location.hash.slice(1).match(ROOM_RE)
  if (m) return m[1] ? 'en' : 'de'
  const q = new URLSearchParams(location.search).get('lang')
  if (q === 'de' || q === 'en') return q
  const saved = get('lang')
  if (saved === 'de' || saved === 'en') return saved
  return /^de\b/i.test(navigator.language || '') ? 'de' : 'en'
}

export let lang = detect()
export const setLang = l => { lang = l; put('lang', l); document.documentElement.lang = l }
document.documentElement.lang = lang

